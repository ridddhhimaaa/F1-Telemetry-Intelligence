"""
Integration Tests for Preprocessing Pipeline (Phase 4)
======================================================
"""

import hashlib
import tempfile
import unittest
from pathlib import Path
import pandas as pd
import numpy as np

import sys
PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from src.preprocessing.preprocess_pipeline import run_preprocessing_pipeline


class TestPreprocessingPipeline(unittest.TestCase):
    """Integration test suite for the complete Phase 4 pipeline."""

    @classmethod
    def setUpClass(cls):
        cls.raw_dir = PROJECT_ROOT / "data" / "raw"
        cls.proc_dir = PROJECT_ROOT / "data" / "processed" / "abu_dhabi_2024"
        cls.rep_dir = PROJECT_ROOT / "reports" / "preprocessing_report"

        cls.expected_hashes = {
            "2024_abu_dhabi_race_laps.csv": "cd92d0a8534374606002b1b39dc51e66185b63fce79f4d67b03cd9ef05abf52c",
            "2024_abu_dhabi_race_laps.parquet": "8f56a5e246e981011090d6a969664f06e1d2915013239db21b94a0e1843be31e",
            "2024_abu_dhabi_race_telemetry.csv": "2104ff24209460a29e821336c73b47ab9310d14d82452fc4bf952af316d09296",
            "2024_abu_dhabi_race_telemetry.parquet": "6fa2d79b98a92741964b03e9cbcfc347928310384e052463b6eef20bf1cde2aa",
        }

    def test_full_pipeline_execution_and_deliverables(self):
        """Verify all datasets, reports, and metadata generated by pipeline."""
        res = run_preprocessing_pipeline()
        self.assertIsNotNone(res)

        # 1. Processed Datasets Verification
        proc_tel_path = self.proc_dir / "processed_telemetry.parquet"
        proc_laps_path = self.proc_dir / "processed_race_laps.parquet"
        resample_path = self.proc_dir / "resampled_telemetry.parquet"
        lap_class_path = self.proc_dir / "lap_classification.csv"

        self.assertTrue(proc_tel_path.is_file())
        self.assertTrue(proc_laps_path.is_file())
        self.assertTrue(resample_path.is_file())
        self.assertTrue(lap_class_path.is_file())

        proc_tel = pd.read_parquet(proc_tel_path)
        proc_laps = pd.read_parquet(proc_laps_path)
        resampled = pd.read_parquet(resample_path)

        # 100% rows preserved
        self.assertEqual(len(proc_tel), 72476)
        self.assertEqual(len(proc_laps), 1035)

        # Verify derived columns
        expected_derived = [
            "IsLeadingRace", "IsTimingLineBoundary", "Distance_Corrected",
            "Distance_Anomaly_Flag", "Throttle_Clipped", "Throttle_Overtravel_Flag",
            "IsBraking", "Brake_Int", "LapClassification", "IsCompleteLap", "IsOutlierFlag"
        ]
        for col in expected_derived:
            self.assertIn(col, proc_tel.columns, f"Missing derived feature: {col}")

        # 2. Resampled Slices Check
        self.assertGreater(len(resampled), 400000)
        self.assertIn("Distance_Meter", resampled.columns)

        # 3. Reports Verification
        expected_reports = [
            "validation_summary.csv",
            "schema_validation.csv",
            "missing_value_treatment.csv",
            "distance_anomaly_report.csv",
            "signal_validation_report.csv",
            "lap_classification_report.csv",
            "outlier_analysis.csv",
            "preprocessing_changes.csv",
            "data_quality_before_after.csv",
            "preprocessing_metadata.json",
            "preprocessing_report.html",
            "resampling_audit.csv",
            "phase4_audit_report.html",
        ]
        for rep_name in expected_reports:
            p = self.rep_dir / rep_name
            self.assertTrue(p.is_file(), f"Missing report: {rep_name}")
            self.assertGreater(p.stat().st_size, 0, f"Empty report: {rep_name}")

    def test_raw_datasets_unmodified(self):
        """Verify SHA256 checksums to guarantee raw data immutability."""
        for file_name, expected_hash in self.expected_hashes.items():
            path = self.raw_dir / file_name
            self.assertTrue(path.is_file(), f"Raw file missing: {file_name}")
            current_hash = hashlib.sha256(path.read_bytes()).hexdigest()
            self.assertEqual(
                current_hash,
                expected_hash,
                f"MUTATION DETECTED: {file_name} modified!"
            )


if __name__ == "__main__":
    unittest.main()
